"""M-PYRE boot splash: assets/mpyre/splash.png (240 x 240, the artwork by History Of Sky) -> the
same header gen_logo.py writes (SLOOP_SPLASH_*: 16 colours, RLE runs of (run - 1) << 4 | index), the
whole screen. Octree to 16 colours, no dither (dither breaks the runs).

  tools/gen_mpyre_splash.py OUT.h [PREVIEW.png]
"""
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parents[1] / "assets/mpyre/splash.png"


def rgb565(c):
    r, g, b = c[:3]
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main(out, preview=None):
    im = Image.open(SRC).convert("RGB")
    if im.size != (240, 240):
        im = im.resize((240, 240), Image.LANCZOS)
    im = im.point(lambda v: v)                        # (a copy) then to the panel's RGB565 steps: no two colours alike
    r, g, b = im.split()
    im = Image.merge("RGB", (r.point(lambda v: v & 0xF8), g.point(lambda v: v & 0xFC), b.point(lambda v: v & 0xF8)))
    q = im.quantize(16, method=Image.FASTOCTREE, dither=Image.NONE)   # (keeps the glow and the flames; the fewest runs)
    pal = q.getpalette()[:48]
    cols = [tuple(pal[3 * k:3 * k + 3]) for k in range(16)]
    order = sorted(range(16), key=lambda k: sum(cols[k]))   # index 0: the darkest (splash.c: drawn too, SLOOP_SPLASH_FULL)
    remap = {old: new for new, old in enumerate(order)}
    cols = [cols[k] for k in order]
    px = [remap[p] for p in q.tobytes()]
    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j
    L = ["/* generated by tools/gen_mpyre_splash.py: the M-PYRE boot splash (artwork: History Of Sky) */", "#pragma once",
         "#include <stdint.h>", "#define SLOOP_SPLASH_W 240", "#define SLOOP_SPLASH_H 240",
         "#define SLOOP_SPLASH_FULL 1      /* the whole screen: version and credits are in the picture */",
         "static const uint16_t SLOOP_SPLASH_PAL[16] = {" + ", ".join(f"0x{rgb565(c):04X}" for c in cols) + "};",
         f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(out).write_text("\n".join(L) + "\n")
    if preview:
        img = Image.new("RGB", (240, 240))
        img.putdata([cols[p] for p in px])
        img.resize((480, 480), Image.NEAREST).save(preview)
    print(f"splash: M-PYRE 240x240, {len(rle)} B RLE -> {out}")


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    main(*sys.argv[1:])
