"""M-PYRE: the amp faces' wordmarks (ui_amp.c), one per face, as 2-bit coverage (4 levels) packed 4 a byte.

  tools/gen_mpyre_amplogo.py OUT.h [PREVIEW.png]

Fonts (assets/mpyre/fonts, SIL Open Font License, each with its OFL text): Pacifico (the tweed face), Damion (the
black-and-gold face), Black Ops One (the metal front), Racing Sans One (the lead), Russo One (the bass amps).
Each is rendered 4x, brought down and its edges contrast-snapped: sharp at 1x, no blur."""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "mpyre" / "fonts"
# face: (font, pixel size, text, tracking px, slant)
FACES = [
    ("Pacifico-Regular.ttf", 26, "M-Pyre", 0, 0.0),        # CLEAN: tweed
    ("Damion-Regular.ttf", 34, "M-Pyre", 0, 0.0),          # CRNCH: black and gold
    ("BlackOpsOne-Regular.ttf", 24, "M-PYRE", 1, 0.0),     # HIGH: the metal front
    ("RacingSansOne-Regular.ttf", 28, "M-PYRE", 0, 0.0),   # LEAD
    ("RussoOne-Regular.ttf", 24, "M-PYRE", 1, 0.0),        # the bass amps
]


def render(font, size, s, tracking, slant):
    S = 4
    f = ImageFont.truetype(str(FONTS / font), size * S)
    w = int(f.getlength(s)) + size * S * 2 + tracking * S * len(s)
    h = size * S * 2
    m = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(m)
    x = size * S
    for ch in s:
        d.text((x, h // 2), ch, font=f, fill=255, anchor="lm")
        x += f.getlength(ch) + tracking * S
    if slant:
        m = m.transform(m.size, Image.AFFINE, (1, slant, -slant * h / 2, 0, 1, 0), Image.BICUBIC)
    m = m.crop(m.getbbox())
    m = m.resize((max(1, (m.width + S - 1) // S), max(1, (m.height + S - 1) // S)), Image.LANCZOS)
    a = np.asarray(m, np.float32) / 255
    a = np.clip((a - 0.5) * 1.8 + 0.5, 0, 1)
    return np.rint(a * 3).astype(np.uint8)           # 0..3


def main():
    out = Path(sys.argv[1])
    L = ["/* generated by tools/gen_mpyre_amplogo.py: the amp faces' wordmarks (fonts: SIL OFL, assets/mpyre/fonts) */",
         "#pragma once", "#include <stdint.h>",
         "typedef struct { uint8_t w, h; uint16_t off; } amplogo_t;   /* 2-bit coverage, 4 pixels a byte, row by row */"]
    data, heads, prev = [], [], []
    for font, size, s, tr, sl in FACES:
        a = render(font, size, s, tr, sl)
        h, w = a.shape
        heads.append((w, h, len(data)))
        flat = list(a.flatten()) + [0] * (-(w * h) % 4)
        for i in range(0, len(flat), 4):
            data.append(flat[i] << 6 | flat[i + 1] << 4 | flat[i + 2] << 2 | flat[i + 3])
        prev.append(a)
    L.append("static const amplogo_t AMPLOGO[%d] = {%s};" % (len(heads), ", ".join("{%d, %d, %d}" % x for x in heads)))
    L.append("static const uint8_t AMPLOGO_DATA[%d] = {" % len(data))
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(str(v) for v in data[i:i + 24]) + ",")
    L.append("};")
    out.write_text("\n".join(L) + "\n")
    print("mpyre amp logos: %d faces, %d B" % (len(heads), len(data)))
    if len(sys.argv) > 2:
        W = max(a.shape[1] for a in prev) + 8
        im = Image.new("L", (W, sum(a.shape[0] + 6 for a in prev)), 0)
        y = 3
        for a in prev:
            im.paste(Image.fromarray(a * 85), (4, y))
            y += a.shape[0] + 6
        im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(sys.argv[2])


if __name__ == "__main__":
    main()
